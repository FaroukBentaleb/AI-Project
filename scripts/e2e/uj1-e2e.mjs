#!/usr/bin/env node
// Story 8.1: API-level UJ-1 end-to-end check through the gateway (generate -> save -> search -> copy/usage ->
// validate), plus the UJ-1 failure path (manual save) and the rejected-generation Safety Note.
//
//   node scripts/e2e/uj1-e2e.mjs                       # stub LLM (docker-compose.e2e.yml), deterministic
//   E2E_MODE=real node scripts/e2e/uj1-e2e.mjs         # real HF provider: only the happy path is asserted
//
// Env: GATEWAY_URL (default http://localhost:8080), FRONTEND_URL (default http://localhost:4200),
//      E2E_MODE (stub|real, default stub). Node 18+ (built-in fetch), no dependencies.
// Exit code 0 when every step passes. Rows created by the run are soft-deleted at the end.

const GATEWAY = (process.env.GATEWAY_URL || 'http://localhost:8080').replace(/\/$/, '');
const FRONTEND = (process.env.FRONTEND_URL || 'http://localhost:4200').replace(/\/$/, '');
const MODE = (process.env.E2E_MODE || 'stub').toLowerCase();
const API = `${GATEWAY}/api/sql`;
const USER = 'e2e-uj1';
const RUN = Date.now().toString(36);
const UJ1_PROMPT = 'orders per region last week vs the week before';
const UNAVAILABLE = 'SQL generation temporarily unavailable. You can save a query manually.';

const created = [];
const results = [];
let failed = 0;

async function call(method, path, body, headers = {}) {
  const t0 = Date.now();
  const res = await fetch(`${API}${path}`, {
    method,
    headers: { 'X-User-Id': USER, ...(body ? { 'Content-Type': 'application/json' } : {}), ...headers },
    body: body ? JSON.stringify(body) : undefined
  });
  const text = await res.text();
  let json = null;
  try {
    json = text ? JSON.parse(text) : null;
  } catch {
    /* not JSON */
  }
  return { status: res.status, json, text, ms: Date.now() - t0 };
}

function check(cond, msg) {
  if (!cond) throw new Error(msg);
}

async function step(name, fn) {
  try {
    const note = await fn();
    results.push({ name, ok: true });
    console.log(`PASS  ${name}${note ? `  (${note})` : ''}`);
  } catch (e) {
    failed++;
    results.push({ name, ok: false });
    console.log(`FAIL  ${name}  -> ${e.message}`);
  }
}

async function waitForGateway(timeoutMs = 180000) {
  const end = Date.now() + timeoutMs;
  for (;;) {
    try {
      if ((await call('GET', '/queries?size=1')).status === 200) return;
    } catch {
      /* not up yet */
    }
    if (Date.now() > end) throw new Error(`gateway route /api/sql not ready at ${GATEWAY}`);
    await new Promise((r) => setTimeout(r, 3000));
  }
}

let generated;
let saved;

console.log(`UJ-1 E2E  mode=${MODE}  gateway=${GATEWAY}  run=${RUN}  ${new Date().toISOString()}`);
await waitForGateway();

await step('0. Frontend served and gateway CORS allows it', async () => {
  const page = await fetch(`${FRONTEND}/`);
  check(page.status === 200, `GET ${FRONTEND}/ -> ${page.status}`);
  check((await page.text()).includes('<app-root'), 'index.html has no <app-root>');
  const pre = await fetch(`${API}/generate`, {
    method: 'OPTIONS',
    headers: {
      Origin: FRONTEND,
      'Access-Control-Request-Method': 'POST',
      'Access-Control-Request-Headers': 'content-type,x-user-id'
    }
  });
  const allow = pre.headers.get('access-control-allow-origin');
  check(pre.status === 200 && (allow === FRONTEND || allow === '*'), `preflight ${pre.status}, allow-origin=${allow}`);
  return `preflight allow-origin=${allow}`;
});

await step('1. Generate (UJ-1 prompt) -> SQL, Warnings, Safety Note, Examples used', async () => {
  const r = await call('POST', '/generate', { prompt: UJ1_PROMPT });
  check(r.status === 200, `status ${r.status}: ${r.text.slice(0, 300)}`);
  const g = r.json;
  check(typeof g.sql === 'string' && /^\s*(select|with)\b/i.test(g.sql), `sql not a SELECT: ${g.sql}`);
  check(g.valid === true && g.source === 'llm-generated', `valid=${g.valid} source=${g.source}`);
  check(typeof g.safety_note === 'string' && g.safety_note.length > 0, 'no safety_note');
  check(Array.isArray(g.warnings) && Array.isArray(g.examples_used), 'warnings / examples_used missing');
  check(g.original_prompt === UJ1_PROMPT, 'original_prompt not echoed');
  if (MODE === 'stub') {
    check(/\borders\b/i.test(g.sql), 'stub SQL should use the orders table');
    check(g.examples_used.length > 0, `no Examples used (warnings: ${JSON.stringify(g.warnings)})`);
  }
  generated = g;
  return `${r.ms} ms, examples_used=${g.examples_used.length}, warnings=${g.warnings.length}, prompt_version=${g.prompt_version}`;
});

await step('2. Save generated SQL (prefill 1: SQL + original prompt, is_llm_generated)', async () => {
  check(generated, 'no generated SQL (step 1 failed)');
  const r = await call('POST', '/queries', {
    title: `E2E UJ-1 orders per region ${RUN}`,
    description: 'Weekly orders per region, generated by the UJ-1 E2E check.',
    sql_content: generated.sql,
    is_llm_generated: true,
    original_nl_prompt: generated.original_prompt
  });
  check(r.status === 201, `status ${r.status}: ${r.text.slice(0, 300)}`);
  saved = r.json;
  created.push(saved.id);
  check(saved.author === USER, `author=${saved.author}`);
  check(saved.is_llm_generated === true && saved.original_nl_prompt === UJ1_PROMPT, 'provenance not stored');
  check(saved.read_only === true, `read_only=${saved.read_only}`);
  if (MODE === 'stub') check(saved.indexed === true, `indexed=false, warnings=${JSON.stringify(saved.warnings)}`);
  return `id=${saved.id}, indexed=${saved.indexed}, ${r.ms} ms`;
});

await step('3. Search the library finds it', async () => {
  check(saved, 'nothing saved (step 2 failed)');
  const r = await call('GET', `/queries?q=${encodeURIComponent(RUN)}`);
  check(r.status === 200, `status ${r.status}`);
  check(r.json.content.some((q) => q.id === saved.id), `id ${saved.id} not in results`);
  return `${r.json.total_elements} hit(s)`;
});

await step('4. Copy records usage', async () => {
  check(saved, 'nothing saved (step 2 failed)');
  const u = await call('POST', `/queries/${saved.id}/usage`);
  check(u.status === 204, `usage status ${u.status}`);
  const g = await call('GET', `/queries/${saved.id}`);
  check(g.json.use_count === 1 && g.json.last_used_at, `use_count=${g.json.use_count}`);
  return 'use_count=1';
});

await step('5. Validate the saved SQL', async () => {
  check(saved, 'nothing saved (step 2 failed)');
  const r = await call('POST', '/validate', { sql_content: saved.sql_content });
  check(r.status === 200, `status ${r.status}`);
  check(r.json.accepted === true && r.json.safety_note, `accepted=${r.json.accepted}`);
  return 'accepted';
});

await step('6. Same prompt again lists the saved query under Examples used (RAG)', async () => {
  check(saved, 'nothing saved (step 2 failed)');
  const r = await call('POST', '/generate', { prompt: UJ1_PROMPT });
  check(r.status === 200, `status ${r.status}`);
  const ids = r.json.examples_used.map((e) => e.id);
  if (MODE === 'stub') check(ids.includes(saved.id), `saved id ${saved.id} not in examples_used ${JSON.stringify(ids)}`);
  return `examples_used=${JSON.stringify(ids)}`;
});

if (MODE === 'stub') {
  await step('7. Rejected generation -> 422 SQL_REJECTED with rejected SQL, reasons and Safety Note', async () => {
    const r = await call('POST', '/generate', { prompt: 'delete the old orders' });
    check(r.status === 422 && r.json.error === 'SQL_REJECTED', `status ${r.status} error=${r.json?.error}`);
    const d = r.json.details;
    check(d.rejected_sql && d.reasons.length > 0, 'no rejected_sql / reasons');
    check(typeof d.safety_note === 'string' && d.safety_note.length > 0, 'details.safety_note missing');
    return d.reasons.map((x) => x.code).join(',');
  });

  await step('8. UJ-1 failure path: LLM down -> 503 LLM_UNAVAILABLE, then manual save', async () => {
    const r = await call('POST', '/generate', { prompt: 'orders during the outage' });
    check(r.status === 503 && r.json.error === 'LLM_UNAVAILABLE', `status ${r.status} error=${r.json?.error}`);
    check(r.json.message === UNAVAILABLE, `message: ${r.json.message}`);
    const m = await call('POST', '/queries', {
      title: `E2E UJ-1 manual save ${RUN}`,
      description: 'Hand-written after an LLM outage (UJ-1 edge case).',
      sql_content: 'SELECT region_id, COUNT(*) FROM orders GROUP BY region_id',
      is_llm_generated: false,
      notes: 'orders during the outage'
    });
    check(m.status === 201 && m.json.is_llm_generated === false, `manual save status ${m.status}`);
    created.push(m.json.id);
    return `retry_after_seconds=${r.json.details?.retry_after_seconds}, manual id=${m.json.id}`;
  });
}

await step('9. Cleanup: soft-delete the rows this run created', async () => {
  for (const id of created) {
    const r = await call('DELETE', `/queries/${id}`);
    check(r.status === 204, `delete ${id} -> ${r.status}`);
  }
  return `${created.length} deleted`;
});

console.log(`\n${results.length - failed}/${results.length} steps passed`);
process.exit(failed ? 1 : 0);
