#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
CREATE USER "$COMMIT_DB_USER" WITH PASSWORD '$COMMIT_DB_PASSWORD';
CREATE USER "$SNIPPET_DB_USER" WITH PASSWORD '$SNIPPET_DB_PASSWORD';
CREATE USER "$BUG_DB_USER" WITH PASSWORD '$BUG_DB_PASSWORD';
CREATE USER "$SQL_DB_USER" WITH PASSWORD '$SQL_DB_PASSWORD';
CREATE USER "$REVIEW_DB_USER" WITH PASSWORD '$REVIEW_DB_PASSWORD';
EOSQL
